/** The atad5s tables the module functions are tested on. */
export function atad5sTables(): Table[] {
  return SHAPE.map(([name, ...fks]) => ({
    name,
    columns: fks.map((fk) => {
      const sep = fk.indexOf('>');
      const rest = fk.slice(sep + 1);
      const dot = rest.lastIndexOf('.');
      return { name: fk.slice(0, sep), type: 'INT', fk: { table: rest.slice(0, dot), column: rest.slice(dot + 1) } };
    }),
  }));
}
